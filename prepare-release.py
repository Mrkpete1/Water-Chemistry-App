"""Run from any folder: python prepare-release.py 5.6.12. Standard library only."""
import hashlib
import json
from pathlib import Path
import re
import sys

root = Path(__file__).resolve().parent
if len(sys.argv) != 2 or not re.fullmatch(r'\d+\.\d+\.\d+', sys.argv[1]):
    raise SystemExit('Usage: python prepare-release.py MAJOR.MINOR.PATCH')
version = sys.argv[1]
index = root / 'index.html'
html = index.read_text(encoding='utf-8')
html, count = re.subn(r'(<meta name="app-version" content=")[^"]+(">)', lambda m: m[1]+version+m[2], html)
if count != 1:
    raise SystemExit('Expected exactly one app-version meta tag.')
html = re.sub(r'(Water Chemistry Assistant · V)\d+\.\d+\.\d+', lambda m: m[1]+version, html)
html = re.sub(r'(id="appVersion">Version )\d+\.\d+\.\d+', lambda m: m[1]+version, html)
index.write_text(html, encoding='utf-8', newline='\n')
# Cache all root app scripts and styles, plus the shell and small required resources.
files = sorted({p.name for pattern in ('*.js','*.css') for p in root.glob(pattern)
                if p.name not in {'sw.js','sw-runtime.js'}} |
               {'index.html','manifest.json','icon.svg','manuals/manifest.json','Taylor-Troubleshooting.pdf'})
release = {'version':version, 'files':{name:hashlib.sha256((root/name).read_bytes()).hexdigest() for name in files}}
sw = '// GENERATED by prepare-release.py; publish with the matching app files.\nconst RELEASE = ' + json.dumps(release, indent=2) + ';\n'
sw += (root/'sw-runtime.js').read_text(encoding='utf-8')
(root/'sw.js').write_text(sw, encoding='utf-8', newline='\n')
(root/'version.json').write_text(json.dumps({'version':version}, indent=2)+'\n', encoding='utf-8', newline='\n')
print(f'Prepared {version}: {len(files)} verified core files. Publish all changed files, sw.js and version.json together.')
